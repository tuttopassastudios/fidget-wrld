/**
 * Report Generator - Creates and updates the markdown audit report
 */

const fs = require('fs');
const path = require('path');
const config = require('../config');

class ReportGenerator {
  constructor() {
    this.startTime = new Date();
    this.products = [];
    this.issues = [];
    this.suggestions = [];
    this.apiLog = [];
    this.status = 'In Progress';
  }

  /**
   * Add a product audit result
   */
  addProductAudit(result) {
    this.products.push(result);

    // Extract issues
    if (result.issues) {
      result.issues.forEach(issue => {
        this.issues.push({
          product: result.slug,
          ...issue,
        });
      });
    }

    // Extract suggestions
    if (result.suggestions) {
      result.suggestions.forEach(suggestion => {
        this.suggestions.push({
          product: result.slug,
          ...suggestion,
        });
      });
    }

    // Save after each product
    this.save();
  }

  /**
   * Set API request log
   */
  setApiLog(log) {
    this.apiLog = log;
  }

  /**
   * Mark audit as complete
   */
  complete() {
    this.status = 'Complete';
    this.endTime = new Date();
    this.save();
  }

  /**
   * Generate the markdown report
   */
  toMarkdown() {
    const now = new Date().toISOString();
    const criticalIssues = this.issues.filter(i => i.severity === 'critical');
    const warnings = this.issues.filter(i => i.severity === 'warning');

    let md = `# CJ Product Audit Report

**Last Updated:** ${now}
**Products Audited:** ${this.products.length} / 7
**Status:** ${this.status}
**Duration:** ${this.getDuration()}

---

## Summary

| Product | Variants | Images | Description | US Stock | Status |
|---------|----------|--------|-------------|----------|--------|
${this.products.map(p => this.productSummaryRow(p)).join('\n')}

---

## Issues Found

${criticalIssues.length > 0 ? `### Critical Issues
${criticalIssues.map(i => `- [ ] **[CRITICAL]** \`${i.product}\`: ${i.message}`).join('\n')}
` : ''}
${warnings.length > 0 ? `### Warnings
${warnings.map(i => `- [ ] **[WARNING]** \`${i.product}\`: ${i.message}`).join('\n')}
` : ''}
${this.issues.length === 0 ? '_No issues found._\n' : ''}

---

## Suggested Changes

${this.suggestions.length > 0 ? this.suggestions.map(s => `### ${s.product}
- **${s.field}:** ${s.summary}
${s.details ? `\n${s.details}\n` : ''}`).join('\n') : '_No changes suggested._'}

---

## Detailed Audits

${this.products.map((p, i) => this.productDetailSection(p, i + 1)).join('\n\n---\n\n')}

---

## Appendix

### A. API Request Log

| Time | Endpoint | Product | Status |
|------|----------|---------|--------|
${this.apiLog.map(l => `| ${l.time} | ${l.endpoint} | ${l.pid || '-'} | ${l.success ? 'OK' : 'FAIL'} |`).join('\n')}

### B. Audit Configuration

- **Min Margin:** ${config.AUDIT.MIN_MARGIN_PERCENT}%
- **Target Margin:** ${config.AUDIT.TARGET_MARGIN_PERCENT}%
- **Low Stock Warning:** ${config.AUDIT.LOW_STOCK_WARNING} units
- **Rate Limit:** ${config.CJ_RATE_LIMIT_MS / 1000}s between calls

---

_Generated by CJ Product QA Agent_
`;

    return md;
  }

  /**
   * Generate summary row for a product
   */
  productSummaryRow(p) {
    const variantStatus = p.variantAudit?.status || 'N/A';
    const imageStatus = p.imageAudit?.summary?.allValid ? 'OK' : 'Issues';
    const descStatus = p.descriptionAudit?.needsRewrite ? 'Needs Review' : 'OK';
    const stockStatus = p.warehouseAudit?.available ? 'Available' : 'Unavailable';
    const overall = p.status || 'PENDING';

    return `| ${p.slug} | ${variantStatus} | ${imageStatus} | ${descStatus} | ${stockStatus} | ${overall} |`;
  }

  /**
   * Generate detailed section for a product
   */
  productDetailSection(p, num) {
    return `### ${num}. ${p.name} (\`${p.slug}\`)

**CJ PID:** \`${p.cjPid || 'Unknown'}\`
**Status:** ${p.status || 'PENDING'}

#### Variant Comparison
${p.variantAudit ? this.variantTable(p.variantAudit) : '_Not audited_'}

#### Image Validation
${p.imageAudit ? this.imageResults(p.imageAudit) : '_Not audited_'}

#### US Warehouse Availability
${p.warehouseAudit ? this.warehouseInfo(p.warehouseAudit) : '_Not audited_'}

#### Description Analysis
${p.descriptionAudit ? this.descriptionInfo(p.descriptionAudit) : '_Not audited_'}
${p.descriptionSuggestion ? `
<details>
<summary>View Suggested Description</summary>

${p.descriptionSuggestion}

</details>
` : ''}`;
  }

  variantTable(audit) {
    if (!audit.comparisons || audit.comparisons.length === 0) {
      return '_No variant data_';
    }

    return `| Our Variant | CJ Match | Price Match | Stock |
|-------------|----------|-------------|-------|
${audit.comparisons.map(c => `| ${c.storeVariant} | ${c.cjMatch ? 'Yes' : 'No'} | ${c.priceMatch ? 'Yes' : 'No'} | ${c.stock || 'N/A'} |`).join('\n')}`;
  }

  imageResults(audit) {
    const { summary } = audit;
    if (summary.allValid) {
      return `All ${summary.total} images valid and accessible.`;
    }

    return `**${summary.invalid}/${summary.total} images have issues:**
${audit.results.filter(r => !r.valid).map(r => `- ${r.variant}: ${r.error}`).join('\n')}`;
  }

  warehouseInfo(audit) {
    if (audit.available) {
      return `- **Available:** Yes
- **Inventory:** ${audit.inventoryNum || audit.totalVerified || 'Unknown'} units`;
    }
    return `- **Available:** No
- **Note:** Product may ship from overseas warehouse`;
  }

  descriptionInfo(audit) {
    if (!audit.hasIssues) {
      return `- **Word Count:** ${audit.wordCount}
- **Status:** OK`;
    }

    return `- **Word Count:** ${audit.wordCount}
- **Issues Found:**
${audit.issues.map(i => `  - ${i}`).join('\n')}`;
  }

  getDuration() {
    const end = this.endTime || new Date();
    const ms = end - this.startTime;
    const mins = Math.floor(ms / 60000);
    const secs = Math.floor((ms % 60000) / 1000);
    return `${mins}m ${secs}s`;
  }

  /**
   * Save report to file
   */
  save() {
    const outputPath = path.join(__dirname, '..', '..', '..', 'reports', 'cj-product-audit.md');

    // Ensure directory exists
    const dir = path.dirname(outputPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }

    fs.writeFileSync(outputPath, this.toMarkdown());
    console.log(`   Report updated: reports/cj-product-audit.md`);
  }
}

module.exports = ReportGenerator;
